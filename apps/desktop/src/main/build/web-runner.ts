export interface SceneNarration {
  /** data: URL of the audio */
  audio: string;
  marks: Record<string, number>;
  captions: { start: number; end: number; text: string }[];
}

/** Generated scenes/index.ts for web animations: plays every scene file in order on one stage. */
export function webRunnerSource(files: string[], narration: Record<string, SceneNarration>): string {
  const imports = files.map((f, i) => `import scene${i}, * as meta${i} from "./${f.replace(/\.ts$/, "")}";`).join("\n");
  const list = files.map((f, i) => `  { id: ${JSON.stringify(f.replace(/\.ts$/, ""))}, run: scene${i}, meta: meta${i} },`).join("\n");
  return `// Generated by Studio. Do not edit: changes are overwritten on every build.
import { Scene } from "manim-web";
${imports}

const scenes = [
${list}
];
const narration: Record<string, { audio: string; marks: Record<string, number>; captions: { start: number; end: number; text: string }[] }> = ${JSON.stringify(narration)};

const stage = document.getElementById("stage")!;
const captionEl = document.getElementById("caption")!;
const scene = new Scene(stage, { backgroundColor: "#0E0E12" });

let audio: HTMLAudioElement | null = null;
let currentId = "";
const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

/** Scenes call scene.waitUntil("mark") to start an animation on a narrated word. */
(scene as any).waitUntil = async (mark: string) => {
  const n = narration[currentId];
  const t = n?.marks[mark];
  if (!audio || t === undefined) return scene.wait(0.4);
  while (!audio.ended && audio.currentTime < t) await sleep(25);
};

function showCaptions() {
  const n = narration[currentId];
  if (!audio || !n) return;
  const tick = () => {
    if (!audio) { captionEl.textContent = ""; return; }
    const c = n.captions.find((c) => audio!.currentTime >= c.start && audio!.currentTime <= c.end + 0.15);
    captionEl.textContent = c ? c.text : "";
    if (!audio.ended) requestAnimationFrame(tick); else captionEl.textContent = "";
  };
  tick();
}

const params = new URLSearchParams(location.search);
const start = Math.max(0, scenes.findIndex((s) => s.id === params.get("scene")));
const only = params.has("only");

async function playAll() {
  for (let i = start; i < scenes.length; i++) {
    currentId = scenes[i].id;
    document.body.dataset.scene = currentId;
    const n = narration[currentId];
    audio = n ? new Audio(n.audio) : null;
    if (audio) { await audio.play().catch(() => {}); showCaptions(); }
    await scenes[i].run(scene);
    while (audio && !audio.ended && !audio.paused) await sleep(50);   // let the narration finish
    audio = null;
    if (only) break;
  }
  document.body.dataset.done = "1";
}

const replay = document.getElementById("replay")!;
const playBtn = document.getElementById("play")!;
replay.addEventListener("click", async () => {
  replay.hidden = true;
  scene.clear();
  await playAll();
  replay.hidden = false;
});

const hasSound = Object.keys(narration).length > 0;
// Browsers only allow sound after a click; the app's preview can start straight away.
if (hasSound && !(window as any).__studioPreview) {
  playBtn.hidden = false;
  playBtn.addEventListener("click", () => {
    playBtn.hidden = true;
    playAll().then(() => { replay.hidden = false; }, (e) => console.error(e));
  }, { once: true });
} else {
  playAll().then(() => { replay.hidden = false; }, (e) => console.error(e));
}
`;
}

