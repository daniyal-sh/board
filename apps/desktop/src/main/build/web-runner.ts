import type { Aspect } from "@studio/shared";

export interface SceneNarration {
  /** data: URL of the audio */
  audio: string;
  duration: number;
  marks: Record<string, number>;
  captions: { start: number; end: number; text: string }[];
}

/**
 * Generated scenes/index.ts for web animations.
 *
 * All scenes are recorded into one manim-web Player timeline, so the result can be paused,
 * scrubbed and jumped scene by scene (the Player's own controls on a shared link; the app's
 * controls in the preview). Narration follows the player's clock: each scene's audio is kept in
 * sync on play, pause and seek, and `waitUntil("mark")` becomes a recorded wait up to the cue.
 */
export function webRunnerSource(files: { file: string; title?: string }[], narration: Record<string, SceneNarration>, aspect: Aspect = "landscape"): string {
  // Vertical keeps Manim's 8-unit frame height, so the frame is 4.5 units wide.
  const frame = aspect === "vertical" ? "frameWidth: 4.5, frameHeight: 8, " : "";
  const imports = files.map((f, i) => `import scene${i}, * as meta${i} from "./${f.file.replace(/\.ts$/, "")}";`).join("\n");
  const list = files.map((f, i) => `  { id: ${JSON.stringify(f.file.replace(/\.ts$/, ""))}, run: scene${i}, meta: meta${i} as { title?: string } },`).join("\n");
  return `// Generated by Board. Do not edit: changes are overwritten on every build.
import { Player, FadeOut } from "manim-web";
// manim-web ships minified, so class names are mangled; layout checks name things by instanceof.
// Named imports (not a namespace import) so unused parts of manim-web are still left out.
import { MathTex as K_MathTex, Tex as K_Tex, MarkupText as K_MarkupText, Paragraph as K_Paragraph, DecimalNumber as K_DecimalNumber, Integer as K_Integer, Text as K_Text, NumberPlane as K_NumberPlane, Axes as K_Axes, NumberLine as K_NumberLine, SurroundingRectangle as K_SurroundingRectangle, Square as K_Square, Rectangle as K_Rectangle, Dot as K_Dot, Circle as K_Circle, Arrow as K_Arrow, Line as K_Line, Polygon as K_Polygon, FunctionGraph as K_FunctionGraph, Brace as K_Brace, VGroup as K_VGroup, Group as K_Group, ReplacementTransform as K_ReplacementTransform, TransformMatchingTex as K_TransformMatchingTex, Transform as K_Transform, DrawBorderThenFill as K_DrawBorderThenFill, Uncreate as K_Uncreate, Create as K_Create, Write as K_Write, FadeIn as K_FadeIn, GrowFromCenter as K_GrowFromCenter, Indicate as K_Indicate, Rotate as K_Rotate, MoveAlongPath as K_MoveAlongPath } from "manim-web";
const K: Record<string, unknown> = { MathTex: K_MathTex, Tex: K_Tex, MarkupText: K_MarkupText, Paragraph: K_Paragraph, DecimalNumber: K_DecimalNumber, Integer: K_Integer, Text: K_Text, NumberPlane: K_NumberPlane, Axes: K_Axes, NumberLine: K_NumberLine, SurroundingRectangle: K_SurroundingRectangle, Square: K_Square, Rectangle: K_Rectangle, Dot: K_Dot, Circle: K_Circle, Arrow: K_Arrow, Line: K_Line, Polygon: K_Polygon, FunctionGraph: K_FunctionGraph, Brace: K_Brace, VGroup: K_VGroup, Group: K_Group, ReplacementTransform: K_ReplacementTransform, TransformMatchingTex: K_TransformMatchingTex, Transform: K_Transform, DrawBorderThenFill: K_DrawBorderThenFill, Uncreate: K_Uncreate, Create: K_Create, Write: K_Write, FadeIn: K_FadeIn, GrowFromCenter: K_GrowFromCenter, Indicate: K_Indicate, Rotate: K_Rotate, MoveAlongPath: K_MoveAlongPath, FadeOut };
${imports}

type Narr = { audio: string; duration: number; marks: Record<string, number>; captions: { start: number; end: number; text: string }[] };
const scenes = [
${list}
];
const narration: Record<string, Narr> = ${JSON.stringify(narration)};
const preview = Boolean((window as any).__studioPreview);
if (preview) document.documentElement.classList.add("studio-preview");
const params = new URLSearchParams(location.search);
const only = params.get("only") ? params.get("scene") : null;

const stage = document.getElementById("stage")!;
const captionEl = document.getElementById("caption")!;
const player = new Player(stage, { ${frame}backgroundColor: "#0E0E12", allowExport: false, autoHideMs: 2200 });

const segments: { id: string; title: string; start: number; end: number }[] = [];
const audios = new Map<string, HTMLAudioElement>();
for (const [id, n] of Object.entries(narration)) {
  const a = new Audio(n.audio);
  a.preload = "auto";
  audios.set(id, a);
}

async function record() {
  await player.sequence(async (rec: any) => {
    const list = scenes.filter((s) => !only || s.id === only);
    for (const [index, s] of list.entries()) {
      const t0 = player.timeline.getDuration();
      const before = new Set<unknown>(player.scene.mobjects);
      const n = narration[s.id];
      const waitUntil = async (mark: string) => {
        const at = n?.marks[mark];
        const delta = at === undefined ? 0.4 : t0 + at - player.timeline.getDuration();
        if (delta > 0.01) await rec.wait(delta);
      };
      // Scenes are written against Scene; forward anything the recorder doesn't handle.
      const scene = new Proxy(rec, {
        get(target, prop) {
          if (prop === "waitUntil") return waitUntil;
          const own = (target as any)[prop];
          if (own !== undefined) return typeof own === "function" ? own.bind(target) : own;
          const real = (player.scene as any)[prop];
          return typeof real === "function" ? real.bind(player.scene) : real;
        },
      });
      await s.run(scene);
      // A scene lasts at least as long as its narration.
      if (n) {
        const need = t0 + n.duration + 0.3 - player.timeline.getDuration();
        if (need > 0.01) await rec.wait(need);
      }
      // Like a cut between Manim scenes: the next scene starts on an empty stage. Recorded as a
      // short fade so scrubbing back brings everything back.
      if (index < list.length - 1) {
        const added = [...player.scene.mobjects].filter((m) => !before.has(m));
        if (added.length) await rec.play(...added.map((m: any) => new FadeOut(m, { duration: 0.35 })));
      }
      segments.push({ id: s.id, title: s.meta.title ?? s.id, start: t0, end: player.timeline.getDuration() });
    }
  });
}

// Most specific first (Square before Rectangle, Dot before Circle…).
const OBJECT_KINDS = ["MathTex", "Tex", "MarkupText", "Paragraph", "DecimalNumber", "Integer", "Text", "NumberPlane", "Axes", "NumberLine", "SurroundingRectangle", "Square", "Rectangle", "Dot", "Circle", "Arrow", "Line", "Polygon", "FunctionGraph", "Brace", "VGroup", "Group"];
const ANIMATION_KINDS = ["ReplacementTransform", "TransformMatchingTex", "Transform", "DrawBorderThenFill", "Uncreate", "Create", "Write", "FadeIn", "FadeOut", "GrowFromCenter", "Indicate", "Rotate", "MoveAlongPath"];
function kindOf(x: any, names: string[]): string | undefined {
  for (const n of names) {
    const C = (K as any)[n];
    if (typeof C === "function" && x instanceof C) return n;
  }
  return undefined;
}
function describeTarget(m: any): string {
  const text = typeof m?._text === "string" ? m._text : typeof m?._latex === "string" ? m._latex : "";
  const kind = kindOf(m, OBJECT_KINDS);
  return text ? \`(“\${text.length > 20 ? text.slice(0, 19) + "…" : text}”)\` : kind ? \`(\${kind})\` : "";
}

/** What is on screen right now, in frame coordinates (0..1 from the top-left), for layout checks. */
function layoutNow() {
  const cam: any = (player.scene as any).camera;
  const fw = cam?.frameWidth ?? 14;
  const fh = cam?.frameHeight ?? 8;
  const cx = cam?.position?.x ?? 0;
  const cy = cam?.position?.y ?? 0;
  const items: { name: string; type: string; box: { x0: number; y0: number; x1: number; y1: number } }[] = [];
  const counts: Record<string, number> = {};
  for (const m of (player.scene as any).mobjects as Set<any>) {
    try {
      if (!(m.opacity > 0.05)) continue;
      const b = m.getBounds();
      if (![b.min.x, b.min.y, b.max.x, b.max.y].every(Number.isFinite)) continue;
      const type = kindOf(m, OBJECT_KINDS) ?? "Object";
      const text = typeof m._text === "string" ? m._text : typeof m._latex === "string" ? m._latex : "";
      counts[type] = (counts[type] ?? 0) + 1;
      const name = text ? \`\${type} “\${text.length > 28 ? text.slice(0, 27) + "…" : text}”\` : \`\${type} #\${counts[type]}\`;
      items.push({
        name,
        type,
        box: { x0: (b.min.x - (cx - fw / 2)) / fw, y0: (cy + fh / 2 - b.max.y) / fh, x1: (b.max.x - (cx - fw / 2)) / fw, y1: (cy + fh / 2 - b.min.y) / fh },
      });
    } catch {
      /* not every object has bounds */
    }
  }
  return items;
}

/** Keep narration and captions on the player's clock. */
function syncAudio() {
  const t = player.timeline.getCurrentTime();
  const seg = segments.find((s) => t >= s.start && t < s.end) ?? null;
  for (const [id, a] of audios) {
    const n = narration[id];
    const local = seg && seg.id === id ? t - seg.start : -1;
    const shouldPlay = player.isPlaying && local >= 0 && local < n.duration;
    if (shouldPlay) {
      if (Math.abs(a.currentTime - local) > 0.25) a.currentTime = local;
      if (a.paused) a.play().catch(() => {});
    } else if (!a.paused) a.pause();
  }
  const n = seg ? narration[seg.id] : undefined;
  const local = seg ? t - seg.start : 0;
  const cap = n?.captions.find((c) => local >= c.start && local <= c.end + 0.15);
  captionEl.textContent = cap ? cap.text : "";
  requestAnimationFrame(syncAudio);
}

// The app's preview drives the player from outside (its own transport and timeline).
let lastState = "";
function postState() {
  if (!preview) return;
  const state = {
    time: Math.round(player.timeline.getCurrentTime() * 100) / 100,
    duration: player.timeline.getDuration(),
    playing: player.isPlaying,
  };
  const key = JSON.stringify(state);
  if (key !== lastState) {
    lastState = key;
    parent.postMessage({ __studio: 1, type: "player.state", ...state }, "*");
  }
}

window.addEventListener("message", (e) => {
  const d = e.data;
  if (!d || !d.__studio || d.type !== "player") return;
  if (d.cmd === "play") player.play();
  else if (d.cmd === "pause") player.pause();
  else if (d.cmd === "toggle") player.togglePlayPause();
  else if (d.cmd === "seek") player.seek(Math.max(0, Math.min(player.timeline.getDuration(), Number(d.time) || 0)));
});

record().then(
  () => {
    const timeline = player.timeline.getSegments().map((s: any) => ({ start: s.startTime, end: s.endTime, wait: s.isWait }));
    // Steps for the assistant's keyframes: each animation, with what it animated.
    const steps = player.timeline
      .getSegments()
      .filter((s: any) => !s.isWait)
      .map((s: any) => ({
        start: s.startTime,
        end: s.endTime,
        scene: segments.find((g) => s.startTime >= g.start - 1e-6 && s.startTime < g.end)?.title ?? "",
        label: (s.animations ?? []).map((a: any) => (kindOf(a, ANIMATION_KINDS) ?? "Animation") + (a?.mobject ? describeTarget(a.mobject) : "")).join(", ") || "Animation",
      }));
    (window as any).__studioPlayer = {
      ready: true,
      scenes: segments,
      steps,
      seek: (t: number) => player.seek(t),
      duration: () => player.timeline.getDuration(),
      layout: () => layoutNow(),
    };
    if (preview) parent.postMessage({ __studio: 1, type: "player.ready", scenes: segments, segments: timeline, duration: player.timeline.getDuration() }, "*");
    player.seek(0);
    // The assistant's inspector loads the preview on its own (not inside the app) and takes
    // pictures over time, so it plays straight away. In the app, the teacher presses play.
    if (preview && window.parent === window && !params.has("still")) player.play();
    setInterval(postState, 80);
    requestAnimationFrame(syncAudio);
  },
  (e) => console.error(e),
);
`;
}

export function webShellHtml(title: string, aspect: Aspect = "landscape"): string {
  const stage =
    aspect === "vertical"
      ? "width: min(100vw, calc(100vh * 9 / 16)); aspect-ratio: 9 / 16;"
      : "width: min(100vw, calc(100vh * 16 / 9)); aspect-ratio: 16 / 9;";
  const safe = title.replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]!);
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${safe}</title>
<style>
  html, body { margin: 0; height: 100%; background: #0E0E12; }
  body { display: grid; place-items: center; font-family: system-ui, sans-serif; overflow: hidden; }
  #stage { ${stage} position: relative; }
  #caption { position: fixed; left: 50%; bottom: 9vh; transform: translateX(-50%); max-width: 80vw; text-align: center; z-index: 5;
    color: #fff; font-size: clamp(16px, 2.6vw, 26px); line-height: 1.35; text-shadow: 0 2px 12px rgba(0,0,0,.8); pointer-events: none; }
  /* Inside the app the preview is driven by the app's own controls. */
  .studio-preview [data-player-bar] { display: none !important; }
</style>
</head>
<body>
<div id="stage" data-part="stage"></div>
<div id="caption" aria-live="polite"></div>
<script type="module" src="./main.ts"></script>
</body>
</html>
`;
}
